# ---------------------------------------------------------------- auto-enroll


def test_auto_enroll_on_capture(client):
    mailbox = MailboxFactory()
    sequence = SequenceFactory()
    SequenceStepFactory(sequence=sequence, order=1)
    source = _source(auto_enroll=sequence, mailbox=mailbox)

    _post_webhook(client, source, {"email": "cto@acme.com"})

    contact = Contact.objects.get(email="cto@acme.com")
    enrollment = Enrollment.objects.get(contact=contact, sequence=sequence)
    assert enrollment.status == Enrollment.Status.ACTIVE
    assert enrollment.mailbox == mailbox
    assert enrollment.next_send_at is not None
    assert Activity.objects.filter(contact=contact, type=Activity.Type.ENROLLED).exists()


def test_no_auto_enroll_without_mailbox(client):
    source = _source(auto_enroll=SequenceFactory())  # no mailbox
    _post_webhook(client, source, {"email": "cto@acme.com"})
    assert not Enrollment.objects.exists()


def test_unsubscribed_contact_not_auto_enrolled(client):
    mailbox = MailboxFactory()
    sequence = SequenceFactory()
    source = _source(auto_enroll=sequence, mailbox=mailbox)
    ContactFactory(email="cto@acme.com", unsubscribed_at=timezone.now())

    _post_webhook(client, source, {"email": "cto@acme.com"})

    assert not Enrollment.objects.exists()


