pytestmark = pytest.mark.django_db


def _source(**kwargs):
    kwargs.setdefault("name", "Landing page")
    kwargs.setdefault("slug", "landing")
    kwargs.setdefault("owner", UserFactory())
    return IntakeSource.objects.create(**kwargs)


def _sign(secret, body: bytes):
    return hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()


def _post_webhook(client, source, payload, signature=None):
    body = json.dumps(payload).encode()
    sig = signature if signature is not None else _sign(source.secret, body)
    return client.post(
        reverse("webhook-intake", args=[source.token]),
        data=body,
        content_type="application/json",
        HTTP_X_BYTEDOCKER_SIGNATURE=sig,
    )


# ---------------------------------------------------------------- model


def test_token_and_secret_autogenerated():
    source = _source()
    assert source.token and source.secret
    assert source.contact_source("webhook") == "webhook:landing"


# ---------------------------------------------------------------- webhook


def test_webhook_good_signature_creates_contact_and_lead(client):
    source = _source()
    response = _post_webhook(
        client,
        source,
        {"email": "CTO@Acme.com", "first_name": "Ada", "company": "Acme", "domain": "acme.com"},
    )
    assert response.status_code == 201
    assert response.json()["created"] is True
    contact = Contact.objects.get(email="cto@acme.com")  # normalized
    assert contact.owner == source.owner
    assert contact.source == "webhook:landing"
    assert contact.first_name == "Ada"
    assert contact.company.domain == "acme.com"
    assert contact.open_lead is not None


def test_webhook_bad_signature_403(client):
    source = _source()
    response = _post_webhook(client, source, {"email": "x@y.com"}, signature="deadbeef")
    assert response.status_code == 403
    assert not Contact.objects.exists()


def test_webhook_existing_contact_fills_blanks_returns_200(client):
    source = _source()
    existing = ContactFactory(email="cto@acme.com", first_name="", title="")
    response = _post_webhook(client, source, {"email": "cto@acme.com", "first_name": "Ada"})
    assert response.status_code == 200
    assert response.json()["created"] is False
    existing.refresh_from_db()
    assert existing.first_name == "Ada"  # blank filled


